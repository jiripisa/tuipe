func readDump(t *testing.T, path string) gen.Dump {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	var d gen.Dump
	if err := json.Unmarshal(data, &d); err != nil {
		t.Fatal(err)
	}
	return d
}

func meta(os string) gen.Meta {
	m := gen.Meta{ID: "test-" + os, Name: "Test " + os, OS: os, ModifierName: "AltGr", Source: "small.json"}
	if os == "darwin" {
		m.ModifierName = "Option"
	}
	return m
}

// generate runs the generator and loads its output with the app's own loader.
func generate(t *testing.T, d gen.Dump, m gen.Meta, keep map[rune]string) (*layout.Layout, string) {
	t.Helper()
	data, err := gen.Generate(d, m, keep)
	if err != nil {
		t.Fatal(err)
	}
	l, err := layout.Parse(data)
	if err != nil {
		t.Fatalf("the generated file does not load: %v\n%s", err, data)
	}
	return l, string(data)
}

func assertRoute(t *testing.T, l *layout.Layout, r rune, want string) {
	t.Helper()
	got, ok := l.Route(r)
	if !ok {
		t.Errorf("%q: no route, want %q", r, want)
		return
	}
	if got.String() != want {
		t.Errorf("%q: route %q, want %q", r, got.String(), want)
	}
}

func assertNoRoute(t *testing.T, l *layout.Layout, r rune) {
	t.Helper()
	if got, ok := l.Route(r); ok {
		t.Errorf("%q: route %q, want none", r, got.String())
	}
}

func assertLabel(t *testing.T, l *layout.Layout, id, want string) {
	t.Helper()
	k, ok := l.Key(id)
	if !ok {
		t.Errorf("no key %s", id)
		return
	}
	if k.Label != want {
		t.Errorf("%s: label %q, want %q", id, k.Label, want)
	}
}

func TestGenerateSmallDump(t *testing.T) {
	d := readDump(t, filepath.Join("testdata", "small.json"))
	for _, tc := range []struct{ os, alt string }{{"linux", "altgr"}, {"darwin", "option"}, {"windows", "altgr"}} {
		t.Run(tc.os, func(t *testing.T) {
			m := meta(tc.os)
			l, text := generate(t, d, m, nil)
			const header = "# Generated by layoutgen from internal/layout/source/small.json. Do not edit.\n"
			if !strings.HasPrefix(text, header) {
				t.Errorf("the file starts %q, want %q", strings.SplitN(text, "\n", 2)[0], header)
			}
			if l.ID != m.ID || l.Name != m.Name || l.OS != m.OS || l.ModifierName != m.ModifierName {
				t.Errorf("identity: %q %q %q %q, want %+v", l.ID, l.Name, l.OS, l.ModifierName, m)
			}
			for id, want := range map[string]string{
				"k2": "d", "k19": "ě", "k24": "´", "k49": "mezera", "k36": "↵", "k0": "",
			} {
				assertLabel(t, l, id, want)
			}
			for r, want := range map[rune]string{
				'd': "k2", 'D': "shift+k2", 'ě': "k19", '2': "shift+k19", '@': tc.alt + "+k19",
				'ď': "shift+k24 k2", 'Ď': "shift+k24 shift+k2", 'ˇ': "shift+k24 k49",
				' ': "k49", '\n': "k36",
			} {
				assertRoute(t, l, r, want)
			}
			// 'a' has no key in the dump, and '´' is not in the character set.
			for _, r := range "a´" {
				assertNoRoute(t, l, r)
			}
			k, _ := l.Key("k2")
			if k.Hand != layout.Left || k.Finger != layout.Middle {
				t.Errorf("k2: hand %v finger %v, want left middle", k.Hand, k.Finger)
			}
		})
	}
}

func TestGenerateIsDeterministic(t *testing.T) {
	d := readDump(t, filepath.Join("testdata", "small.json"))
	first, err := gen.Generate(d, meta("linux"), nil)
	if err != nil {
		t.Fatal(err)
	}
	for range 20 {
		again, err := gen.Generate(d, meta("linux"), nil)
		if err != nil {
			t.Fatal(err)
		}
		if string(again) != string(first) {
			t.Fatalf("two runs differ:\n%s\n---\n%s", first, again)
		}
	}
}

// twoWaysToTypeÁ has á on its own key and behind the dead key k1.
var twoWaysToTypeÁ = gen.Dump{
	Keys: map[string]gen.Levels{
		"k0": {"": "a"},
		"k1": {"": ""},
		"k2": {"": "á"},
	},
	Dead: map[string]map[string]string{"k1": {"k0": "á"}},
}

func TestKeepWinsOverShorterRoute(t *testing.T) {
	l, _ := generate(t, twoWaysToTypeÁ, meta("linux"), map[rune]string{'á': "k1 k0"})
	assertRoute(t, l, 'á', "k1 k0")

	l, _ = generate(t, twoWaysToTypeÁ, meta("linux"), nil)
	assertRoute(t, l, 'á', "k2")
}

func TestKeepThatNoLongerTypesIsIgnored(t *testing.T) {
	l, _ := generate(t, twoWaysToTypeÁ, meta("linux"), map[rune]string{'a': "k5", 'á': "k2 k0"})
	assertRoute(t, l, 'a', "k0")
	assertRoute(t, l, 'á', "k2")
}

func TestKeepIgnoresModifierOrder(t *testing.T) {
	d := gen.Dump{Keys: map[string]gen.Levels{"k0": {"": "x"}, "k1": {"shift+alt": "x"}}}
	l, _ := generate(t, d, meta("darwin"), map[rune]string{'x': "option+shift+k1"})
	assertRoute(t, l, 'x', "shift+option+k1")
}

func TestModifierRankBreaksTies(t *testing.T) {
	// k0 comes before k6 in position order, so the better modifier on k6 has to
	// win against position order.
	d := gen.Dump{Keys: map[string]gen.Levels{
		"k0": {"shift": "q", "alt": "w", "shift+alt": "e"},
		"k6": {"": "q", "shift": "w", "alt": "e"},
	}}
	l, _ := generate(t, d, meta("linux"), nil)
	assertRoute(t, l, 'q', "k6")
	assertRoute(t, l, 'w', "shift+k6")
	assertRoute(t, l, 'e', "altgr+k6")
}

func TestTieBreaksAroundModifiers(t *testing.T) {
	d := gen.Dump{
		Keys: map[string]gen.Levels{
			"k10": {"": "r"}, "k6": {"": "r"}, // r: avoid k10
			"k50": {"": "t"}, "k7": {"": "t"}, // t: avoid k50
			"k8": {"": "u"}, "k0": {"": "u"}, // u: position order
			"k9": {"shift+alt": "z"}, // z: one chord beats two without modifiers
			"k1": {"": ""},
		},
		Dead: map[string]map[string]string{"k1": {"k0": "z"}},
	}
	l, _ := generate(t, d, meta("linux"), nil)
	assertRoute(t, l, 'r', "k6")
	assertRoute(t, l, 't', "k7")
	assertRoute(t, l, 'u', "k0")
	assertRoute(t, l, 'z', "shift+altgr+k9")
}

// TestDeadLevelTypesNothingOnItsOwn: a dumper may write the dead key's own
// character at its level, but pressing it alone still types nothing.
func TestDeadLevelTypesNothingOnItsOwn(t *testing.T) {
	d := gen.Dump{
		Keys: map[string]gen.Levels{"k42": {"": "¨", "shift": "`"}},
		Dead: map[string]map[string]string{"k42": {"k49": "¨"}},
	}
	l, _ := generate(t, d, meta("darwin"), nil)
	assertRoute(t, l, '¨', "k42 k49")
	assertRoute(t, l, '`', "shift+k42")
	assertLabel(t, l, "k42", "¨")
}

// TestDeadKeyLabelIsTheAccentItAdds: macOS types an apostrophe for acute and
// space, so the label comes from what the dead key does to a, and from space
// only when that says nothing.
func TestDeadKeyLabelIsTheAccentItAdds(t *testing.T) {
	d := gen.Dump{
		Keys: map[string]gen.Levels{"k24": {"": ""}, "k42": {"": ""}, "k27": {"": ""}, "k39": {"": ""}},
		Dead: map[string]map[string]string{
			"k24": {"k49": "'", "k0": "á"},
			"k42": {"k49": "\"", "k0": "¨a", "shift+k0": "Ä"},
			"k27": {"k49": "°"},
			"k39": {"k49": "x", "k0": "x"},
		},
	}
	l, _ := generate(t, d, meta("darwin"), nil)
	assertLabel(t, l, "k24", "´")
	assertLabel(t, l, "k42", "¨")
	assertLabel(t, l, "k27", "°")
	assertLabel(t, l, "k39", "x")
}

func TestModifierBeatsAvoidingK10(t *testing.T) {
	d := gen.Dump{Keys: map[string]gen.Levels{"k10": {"": "<"}, "k43": {"alt": "<"}}}
	l, _ := generate(t, d, meta("darwin"), nil)
	assertRoute(t, l, '<', "k10")
}

// edges types on k10 and k50, and has other ways to type some of it.
var edges = gen.Dump{Keys: map[string]gen.Levels{
	"k10": {"": "<", "shift": ">"},
	"k50": {"": "\\", "shift": "|", "alt": ">"},
	"k43": {"alt": "<"},
	"k8":  {"alt": "\\"},
}}

func TestANSISectionByOS(t *testing.T) {
	t.Run("darwin", func(t *testing.T) {
		l, text := generate(t, edges, meta("darwin"), nil)
		if !strings.Contains(text, "\n[ansi]\nmoved = { k50 = \"k10\" }\n") {
			t.Errorf("no moved k50 in:\n%s", text)
		}
		if strings.Contains(text, "missing") {
			t.Errorf("darwin has missing keys:\n%s", text)
		}
		if n := strings.Count(text, "[[ansi.char]]"); n != 2 {
			t.Errorf("%d [[ansi.char]], want 2:\n%s", n, text)
		}
		assertRoute(t, l, '<', "k10")
		assertRoute(t, l, '>', "shift+k10")
		us := l.WithShape(layout.ANSI)
		assertRoute(t, us, '<', "option+k43")
		// On ISO, > is also option+k50; on the US shape that key sits at k10.
		assertRoute(t, us, '>', "option+k10")
		assertRoute(t, us, '\\', "k10")
		assertRoute(t, us, '|', "shift+k10")
	})
	for _, os := range []string{"linux", "windows"} {
		t.Run(os, func(t *testing.T) {
			l, text := generate(t, edges, meta(os), nil)
			if !strings.Contains(text, "\n[ansi]\nmissing = [\"k50\"]\n") {
				t.Errorf("no missing k50 in:\n%s", text)
			}
			if strings.Contains(text, "moved") {
				t.Errorf("%s has moved keys:\n%s", os, text)
			}
			if n := strings.Count(text, "[[ansi.char]]"); n != 1 {
				t.Errorf("%d [[ansi.char]], want 1:\n%s", n, text)
			}
			assertRoute(t, l, '\\', "k50")
			us := l.WithShape(layout.ANSI)
			assertRoute(t, us, '\\', "altgr+k8")
			assertNoRoute(t, us, '|')
			assertRoute(t, us, '<', "k10")
			assertRoute(t, us, '>', "shift+k10")
		})
	}
}

// TestPositionsCoverEveryKeyOnce compares the positions with the rows of the
// layout file that shipped before the generator: same keys, order, hands and fingers.
func TestPositionsCoverEveryKeyOnce(t *testing.T) {
	data, err := os.ReadFile(filepath.Join("..", "data", "macos-czech-qwerty.toml"))
	if err != nil {
		t.Fatal(err)
	}
	shipped, err := layout.Parse(data)
	if err != nil {
		t.Fatal(err)
	}
	generated, _ := generate(t, gen.Dump{}, meta("darwin"), nil)

	var ids []string
	for _, row := range generated.Rows {
		for _, k := range row {
			ids = append(ids, k.ID)
		}
	}
	if len(ids) != 50 {
		t.Errorf("%d keys, want 50", len(ids))
	}
	sorted := slices.Clone(ids)
	slices.Sort(sorted)
	if len(slices.Compact(sorted)) != len(ids) {
		t.Errorf("repeated ids in %v", ids)
	}
	for _, id := range []string{"k49", "k36", "k10", "k50", "k42"} {
		if !slices.Contains(ids, id) {
			t.Errorf("no %s", id)
		}
	}

	if len(generated.Rows) != len(shipped.Rows) {
		t.Fatalf("%d rows, want %d", len(generated.Rows), len(shipped.Rows))
	}
	for i, row := range shipped.Rows {
		if len(generated.Rows[i]) != len(row) {
			t.Errorf("row %d: %d keys, want %d", i, len(generated.Rows[i]), len(row))
			continue
		}
		for j, want := range row {
			got := generated.Rows[i][j]
			if got.ID != want.ID || got.Hand != want.Hand || got.Finger != want.Finger {
				t.Errorf("row %d key %d: %s %v %v, want %s %v %v",
					i, j, got.ID, got.Hand, got.Finger, want.ID, want.Hand, want.Finger)
			}
		}
	}

	var flat []string
	for _, row := range gen.Positions() {
		for _, p := range row {
			flat = append(flat, p.ID)
		}
	}
	if !slices.Equal(flat, ids) {
		t.Errorf("Positions() = %v, want %v", flat, ids)
	}
}

