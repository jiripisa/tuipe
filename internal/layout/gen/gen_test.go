// writeTree makes an internal/layout folder with one layout in its manifest.
func writeTree(t *testing.T, d gen.Dump) (dir string, m gen.Meta) {
	t.Helper()
	dir = t.TempDir()
	for _, sub := range []string{"source", "data"} {
		if err := os.Mkdir(filepath.Join(dir, sub), 0o755); err != nil {
			t.Fatal(err)
		}
	}
	dump, err := json.Marshal(d)
	if err != nil {
		t.Fatal(err)
	}
	m = gen.Meta{ID: "test-linux", Name: "Test linux", OS: "linux", ModifierName: "AltGr", Source: "test-linux.json"}
	manifest := `[[layout]]
id = "test-linux"
name = "Test linux"
os = "linux"
modifier_name = "AltGr"
source = "test-linux.json"
`
	write(t, filepath.Join(dir, "source", "test-linux.json"), dump)
	write(t, filepath.Join(dir, "source", "layouts.toml"), []byte(manifest))
	return dir, m
}

func write(t *testing.T, path string, data []byte) {
	t.Helper()
	if err := os.WriteFile(path, data, 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestBuildKeepsTheRoutesOfTheExistingFile(t *testing.T) {
	dir, m := writeTree(t, twoWaysToTypeÁ)
	path := filepath.Join(dir, "data", "test-linux.toml")
	old, err := gen.Generate(twoWaysToTypeÁ, m, map[rune]string{'á': "k1 k0"})
	if err != nil {
		t.Fatal(err)
	}
	write(t, path, old)

	files, err := gen.Build(dir)
	if err != nil {
		t.Fatal(err)
	}
	if len(files) != 1 || files[0].Path != path {
		t.Fatalf("files %v, want one at %s", files, path)
	}
	if string(files[0].Data) != string(old) {
		t.Errorf("the existing route was not kept:\n%s", files[0].Data)
	}
	if stale, err := gen.Stale(files); err != nil || len(stale) != 0 {
		t.Errorf("stale %v, err %v, want none", stale, err)
	}
}

func TestStaleNamesMissingAndChangedFiles(t *testing.T) {
	dir, _ := writeTree(t, twoWaysToTypeÁ)
	path := filepath.Join(dir, "data", "test-linux.toml")
	files, err := gen.Build(dir)
	if err != nil {
		t.Fatal(err)
	}
	if stale, err := gen.Stale(files); err != nil || !slices.Equal(stale, []string{path}) {
		t.Errorf("missing file: stale %v, err %v, want %s", stale, err, path)
	}
	write(t, path, append(slices.Clone(files[0].Data), '\n'))
	if stale, err := gen.Stale(files); err != nil || !slices.Equal(stale, []string{path}) {
		t.Errorf("changed file: stale %v, err %v, want %s", stale, err, path)
	}
	write(t, path, files[0].Data)
	if stale, err := gen.Stale(files); err != nil || len(stale) != 0 {
		t.Errorf("current file: stale %v, err %v, want none", stale, err)
	}
}

func TestBuildRejectsABadManifest(t *testing.T) {
	for name, manifest := range map[string]string{
		"unknown field": "[[layout]]\nid = \"x\"\nname = \"X\"\nsource = \"x.json\"\nshape = \"iso\"\n",
		"no source":     "[[layout]]\nid = \"x\"\nname = \"X\"\n",
		"twice":         "[[layout]]\nid = \"x\"\nname = \"X\"\nsource = \"x.json\"\n[[layout]]\nid = \"x\"\nname = \"X\"\nsource = \"x.json\"\n",
	} {
		dir, _ := writeTree(t, twoWaysToTypeÁ)
		write(t, filepath.Join(dir, "source", "x.json"), []byte("{}"))
		write(t, filepath.Join(dir, "source", "layouts.toml"), []byte(manifest))
		if _, err := gen.Build(dir); err == nil {
			t.Errorf("%s: no error", name)
		}
	}
}

